def _disk_c_star(sweep, policy_row, capacity):
    """Pooled c* of a disk policy against none, from per-trace sweep counts:
    (mean hit gain) / (mean extra prefetches per read block)."""
    rows = [r for r in sweep or () if r["config"] == g.HEADLINE_CONFIG
            and r["merge"] == g.HEADLINE_MERGE and r["latency"] == g.HEADLINE_LATENCY
            and r["capacity"] == capacity and r["status"] == "ok"]
    label = {r["trace"]: r for r in rows if r["mode"] == "none"}

    def name(r):
        if r["mode"] == "deep":
            return f"deep@{r['depth']}"
        if r["mode"] == "linux_ra":
            return f"linux_ra@{r['max_blocks']}"
        return r["mode"]

    pairs = [(r, label[r["trace"]]) for r in rows
             if name(r) == policy_row["policy"] and r["trace"] in label]
    if not pairs:
        return None
    gain = statistics.fmean(p["hit_ratio"] - n["hit_ratio"] for p, n in pairs)
    extra = statistics.fmean(p["total_prefetches"] / p["read_blocks"]
                             - n["total_prefetches"] / n["read_blocks"] for p, n in pairs)
    return gain / extra if extra else None


def t8_cross_domain(results, out):
    caption = ("Cross-domain summary. Disk and web rows are simulated, live rows measured on "
               "loopback with an ASSUMED network. Gain is against no prefetching with a 95\\% CI; "
               "c*: the cost per prefetch at which the policy ties no prefetching.")
    table = Table("lllrrrr", ["Domain / setting", "Best policy", "Gain unit",
                              "Gain over none", "Waste", "c*", "Feedback gate"])
    any_rows = False
    disk = _headline(results.rows("disk/table_main.csv", out), corpus="all",
                     latency=g.HEADLINE_LATENCY)
    sweep = results.rows("disk/sweep.jsonl", out, required=False)
    for capacity in sorted({r["capacity"] for r in disk}):
        items = [r for r in disk if r["capacity"] == capacity and r["mean_hit_ratio"] is not None]
        if not items:
            continue
        any_rows = True
        best = max(items, key=lambda r: (r["mean_hit_ratio"], -g.policy_key(r["policy"])[0]))
        guard = next((r for r in items if r["policy"] == "guard"), None)
        c_star = _disk_c_star(sweep, best, capacity)
        table.row([f"Disk, {g.capacity_label(capacity)}", esc(best["policy"]), "hit ratio, pp",
                   ci_cell(best["delta_vs_none"], best["delta_vs_none_lo"],
                           best["delta_vs_none_hi"]),
                   fpct(best["mean_wasted_share"]).replace(r"\,\%", "\\,\\% unused")
                   if best["mean_wasted_share"] is not None else DASH,
                   fnum(c_star, 3) if c_star is not None else DASH,
                   ci_cell(guard["delta_vs_none"], guard["delta_vs_none_lo"],
                           guard["delta_vs_none_hi"]) if guard else DASH])
    comparisons = g.select(results.rows("web/comparisons.csv", out), split="test",
                           selection="per_capacity")
    metrics = g.select(results.rows("web/policy_metrics.csv", out, required=False),
                       split="test", cache_scope="session")
    decomposition = results.rows("web/decomposition.csv", out, required=False)
    feedback = [r for r in decomposition or () if r["lever"] == "feedback"]
    for capacity in sorted({r["capacity"] for r in comparisons}):
        choices = [r for r in comparisons if r["capacity"] == capacity and r["cost"] > 0] or \
                  [r for r in comparisons if r["capacity"] == capacity]
        row = min(choices, key=lambda r: (r["scorer"] != "logistic", r["cost"]))
        any_rows = True
        metric = next((m for m in metrics if m["scorer"] == row["scorer"]
                       and m["capacity"] == capacity and m["policy"] == row["adaptive_policy"]),
                      None)
        gate = next((f for f in feedback if f["capacity"] == capacity), None)
        table.row([f"Web, cap.\\ {fcount(capacity)}, c = {row['cost']:g}",
                   esc(row["adaptive_policy"]), "U per view, pp",
                   ci_cell(row["vs_fixed0"], row["vs_fixed0_lo"], row["vs_fixed0_hi"]),
                   (fnum(metric["wasted_per_view"], 2) + " /view") if metric else DASH,
                   fnum(metric["c_star"], 4) if metric and metric["c_star"] is not None else DASH,
                   ci_cell(gate["estimate"], gate["ci_lo"], gate["ci_hi"]) if gate else DASH])
    live_rows = results.rows("live/live_metrics.csv", out)
    groups = _live_groups(live_rows or (), ("headline",))
    for store in sorted({k[1] for k in groups}):
        scored = {k: g.live_saved(v) for k, v in groups.items() if k[1] == store}
        scored = {k: v for k, v in scored.items() if v is not None}
        if not scored:
            continue
        best = max(scored, key=lambda k: scored[k][0])
        gate = next((k for k in scored if "feedback" in k[4]), None)
        any_rows = True
        items = groups[best]
        table.row([f"Live HTTP, {esc(store)} store", esc(best[4]), "ms per view",
                   ci_cell(*scored[best], fnum, digits=2),
                   fnum(statistics.fmean(r["wasted_kb_per_view"] for r in items), 1) + " KiB",
                   DASH, ci_cell(*scored[gate], fnum, digits=2) if gate else DASH])
    if not any_rows:
        return placeholder("t8_cross_domain", caption, out, wide=True)
    return float_env("t8_cross_domain", caption, table.latex(), wide=True, out=out,
                     note="Disk: C1 canonical, best by mean hit ratio, gate = guard. Web: the "
                          "validation-selected controller at the smallest positive cost, gate = "
                          "feedback lever. Live: best valid policy by mean saving.")


