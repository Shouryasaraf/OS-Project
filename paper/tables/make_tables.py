def t2_disk_main(results, out):
    caption = ("Disk results (simulated LRU cache, C1 configuration, canonical requests). Mean block hit "
               "ratio over traces; $\\Delta$ in percentage points with 95\\% paired-bootstrap CIs "
               "over traces; device-I/O and blocks-moved ratios are means over traces of the "
               "policy's count over \\texttt{none}'s. $^\\dagger$ gated mode at the break-even "
               "cost model. $^\\ddagger$ Belady's MIN for demand paging without prefetch, "
               "on the same block stream: a reference for replacement, not a bound on "
               "prefetching policies, several of which exceed it. Writes replay as reads.")
    rows = results.rows("disk/table_main.csv", out)
    rows = _headline(rows, corpus="all")
    if not rows:
        if "disk/table_main.csv" not in out.missing:
            out.missing.append("disk/table_main.csv: no C1/auto rows")
        return placeholder("t2_disk_main", caption, out, wide=True)
    table = Table("lrrrrrrrr", [
        "Policy", "Hit (\\%)", "$\\Delta$ vs none (pp)", "$\\Delta$ vs seq.\\ (pp)",
        "Prec.\\ (\\%)", "Waste (\\%)", "Dev.\\ I/O", "Blocks", "W/L vs none"])
    capacities = sorted({r["capacity"] for r in rows})
    for capacity in capacities:
        items = [r for r in rows if r["capacity"] == capacity
                 and (r["latency"] == g.HEADLINE_LATENCY or r["policy"].split("@")[0]
                      in g.GATED_MODES)]
        n = max(r["n_traces"] for r in items)
        table.group(f"{g.capacity_label(capacity)} cache ({fcount(capacity)} blocks), "
                    f"n = {fcount(n)} traces")
        for row in sorted_policies(items):
            if row["mean_hit_ratio"] is None:
                table.row([policy_label(row["policy"], row["latency"]), "skipped"]
                          + [DASH] * 7)
                continue
            wl = (f"{fcount(row['wins_vs_none'])}/{fcount(row['losses_vs_none'])}"
                  if row["wins_vs_none"] is not None else DASH)
            table.row([policy_label(row["policy"], row["latency"]),
                       fnum(100 * row["mean_hit_ratio"], 2),
                       ci_cell(row["delta_vs_none"], row["delta_vs_none_lo"],
                               row["delta_vs_none_hi"]),
                       ci_cell(row["delta_vs_sequential"], row["delta_vs_sequential_lo"],
                               row["delta_vs_sequential_hi"]),
                       fnum(None if row["mean_precision"] is None
                            else 100 * row["mean_precision"], 1),
                       fnum(None if row["mean_wasted_share"] is None
                            else 100 * row["mean_wasted_share"], 1),
                       fratio(row["device_io_ratio"]), fratio(row["blocks_moved_ratio"]), wl])
    return float_env("t2_disk_main", caption, table.latex(), wide=True, out=out, dense=True,
                     note=f"Bootstrap: {_resamples(results, out)}. W/L: traces where the policy's "
                          "hit ratio is above/below none's.")


def t2b_disk_by_corpus(results, out):
    caption = ("Disk mean block hit ratio (\\%, simulated) per corpus, C1, canonical requests; "
               "n traces per corpus in the header. $^\\ddagger$ demand-only Belady MIN, a "
               "reference for replacement and not a bound on prefetching.")
    rows = _headline(results.rows("disk/table_by_corpus.csv", out), latency=g.HEADLINE_LATENCY)
    if not rows:
        return placeholder("t2b_disk_by_corpus", caption, out, wide=True)
    capacities = sorted({r["capacity"] for r in rows})
    corpora = sorted({r["corpus"] for r in rows})
    n = {c: max(r["n_traces"] for r in rows if r["corpus"] == c) for c in corpora}
    # Two header rows: the capacities span their corpora, then one column each.
    table = Table("l" + "r" * (len(capacities) * len(corpora)), [
        [""] + [rf"\multicolumn{{{len(corpora)}}}{{c}}{{{g.capacity_label(c)}}}"
                for c in capacities],
        ["Policy"] + [f"{esc(c)} ({fcount(n[c])})" for _ in capacities for c in corpora]])
    cell = {(r["policy"], r["capacity"], r["corpus"]): r["mean_hit_ratio"] for r in rows}
    for policy in sorted({r["policy"] for r in rows}, key=g.policy_key):
        values = [cell.get((policy, cap, corpus)) for cap in capacities for corpus in corpora]
        table.row([policy_label(policy)] + [fnum(None if v is None else 100 * v, 2)
                                            for v in values])
    return float_env("t2b_disk_by_corpus", caption, table.latex(), wide=True, out=out)


def t2c_learned_depth(results, out):
    caption = ("learned\\_depth against the validation-chosen fixed depth (VCF) on each trace's "
               "held-out test segment (simulated block hit ratio, \\%, mean over seeds). "
               "Oracle: E2's hindsight same-actions reference; it is not a bound and can "
               "fall below the learned controller.")
    rows = results.rows("gpu/disk_learned_depth.csv", out)
    if not rows:
        return placeholder("t2c_learned_depth", caption, out, wide=True)
    table = Table("llrrrrrrr", ["Trace", "Corpus", "Seeds", "learned", "VCF (depth)",
                                "deep@8", "none", "Oracle", "$\\Delta$ vs VCF (pp)"])
    for cap in sorted({r["action_cap"] for r in rows}):
        table.group(f"action cap {fcount(cap)} blocks")
        per_trace = defaultdict(list)
        for row in g.select(rows, action_cap=cap):
            per_trace[(row["trace"], row["corpus"])].append(row)
        for (trace, corpus), items in sorted(per_trace.items()):
            ok = [r for r in items if r["status"] == "ok"]
            if not ok:
                table.row([esc(trace), esc(corpus), "0",
                           esc(items[0]["status"])] + [DASH] * 5)
                continue

            def mean(key):
                values = [r[key] for r in ok if r[key] is not None]
                return statistics.fmean(values) if values else None

            depths = sorted({r["vcf_depth"] for r in ok if r["vcf_depth"] is not None})
            learned, vcf = mean("test_hit_ratio"), mean("vcf_hit_ratio")
            table.row([esc(trace), esc(corpus), fcount(len(ok)),
                       fnum(100 * learned, 2) if learned is not None else DASH,
                       (fnum(100 * vcf, 2) if vcf is not None else DASH)
                       + (f" ({'/'.join(map(str, depths))})" if depths else ""),
                       *(fnum(100 * v, 2) if v is not None else DASH
                         for v in (mean("deep8_hit_ratio"), mean("none_hit_ratio"),
                                   mean("oracle_same_actions_hit_ratio"))),
                       fpp(learned - vcf).replace(r"\,pp", "")
                       if learned is not None and vcf is not None else DASH])
    return float_env("t2c_learned_depth", caption, table.latex(), wide=True, out=out)


