def t4_web_dataset(results, out):
    caption = ("RetailRocket dataset profile and pair kinds, every numeric field of "
               "results/web/dataset\\_profile.json as written.")
    payload = results.json_object("web/dataset_profile.json", out)
    if payload is None:
        return placeholder("t4_web_dataset", caption, out, wide=False)
    table = Table("lr", ["Field", "Value"])

    def walk(node, prefix=()):
        for key, value in node.items():
            if isinstance(value, dict):
                yield from walk(value, prefix + (key,))
            elif isinstance(value, (int, float)) and not isinstance(value, bool):
                yield prefix + (key,), value

    for path, value in walk(payload):
        fraction = any(word in path[-1] for word in ("frac", "share", "ratio"))
        text = (fcount(value) if isinstance(value, int)
                else fpct(value) if fraction and abs(value) <= 1 else fnum(value, 3))
        table.row([esc(" / ".join(map(str, path))), text])
    return float_env("t4_web_dataset", caption, table.latex(), wide=False, out=out)


