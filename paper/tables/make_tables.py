"""Write the paper's tables, ``paper/tables/*.tex``, from ``results/**``.

    PYTHONPATH=src python paper/tables/make_tables.py [--results DIR] [--paper-dir DIR]

One function per table (MASTER_PLAN section 5, T1-T8, plus the supporting
tables the sections name). Each file is a complete float -- ``table`` or
``table*`` with ``\\caption`` and ``\\label{tab:<name>}`` -- so a section only
writes ``\\input{tables/<name>}`` and ``\\ref{tab:<name>}``. Tables use plain
``\\hline`` rules: IEEEtran does not ship booktabs.

A table whose input is missing is still written, with the same label and a
single row reading "MISSING: <file>", so the paper always compiles and the
gap is visible. Built from a fixture tree, every caption starts with
"FIXTURE DATA". Numbers are formatted by ``genlib``: fractions as percent
(levels) or percentage points (differences), ratios as multipliers. Every
value is printed as the results file holds it; nothing is filled in.

Stdlib only.
"""

from __future__ import annotations

import argparse
import importlib.util
import statistics
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent


def _genlib():
    """``paper/genlib.py``, loaded by path: putting ``paper/`` on sys.path
    would let ``paper/numbers.py`` shadow the stdlib ``numbers`` module."""
    if "paper_genlib" not in sys.modules:
        spec = importlib.util.spec_from_file_location("paper_genlib", HERE.parent / "genlib.py")
        module = importlib.util.module_from_spec(spec)
        sys.modules["paper_genlib"] = module
        spec.loader.exec_module(module)
    return sys.modules["paper_genlib"]


g = _genlib()
esc, fnum, fpct, fpp, fratio, fcount, fci = g.esc, g.fnum, g.fpct, g.fpp, g.fratio, g.fcount, g.fci
DASH = g.DASH


