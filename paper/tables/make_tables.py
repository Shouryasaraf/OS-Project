class Table:
    """A tabular under construction: column spec, header rows, body rows."""

    def __init__(self, spec: str, header: list[list[str]] | list[str]):
        self.spec = spec
        self.columns = len([c for c in spec if c in "lcrp"])
        self.header = header if header and isinstance(header[0], list) else [header]
        self.body: list[str] = []

    def row(self, cells) -> None:
        cells = list(cells)
        if len(cells) != self.columns:
            raise ValueError(f"{len(cells)} cells for {self.columns} columns: {cells}")
        self.body.append(" & ".join(cells) + r" \\")

    def group(self, title: str) -> None:
        """A full-width group heading (a capacity, a think-time model)."""
        self.body.append(r"\hline")
        self.body.append(rf"\multicolumn{{{self.columns}}}{{l}}{{\emph{{{title}}}}} \\")
        self.body.append(r"\hline")

    def latex(self) -> str:
        lines = [rf"\begin{{tabular}}{{{self.spec}}}", r"\hline"]
        lines += [" & ".join(cells) + r" \\" for cells in self.header]
        if not self.body or self.body[0] != r"\hline":
            lines.append(r"\hline")
        lines += self.body
        lines += [r"\hline", r"\end{tabular}"]
        return "\n".join(lines)


def ci_cell(estimate, lo, hi, formatter=fpp, **kwargs) -> str:
    """``estimate`` with its interval in small type underneath it on one line."""
    if estimate is None:
        return DASH
    text = formatter(estimate, **kwargs).replace(r"\,pp", "").replace(r"\,\%", "")
    interval = fci(lo, hi, formatter, **kwargs)
    return text + (r" {\scriptsize " + interval + "}" if interval else "")


#: Font size and column gap of a dense table, so the widest tables fit the
#: IEEE text width (7.16 in) or column width (3.5 in) without a resize.
DENSE = ("scriptsize", 2)


def float_env(name: str, caption: str, body: str, *, wide: bool, out: "g.Output",
              note: str | None = None, dense: bool = False) -> str:
    env = "table*" if wide else "table"
    if out.fixture:
        caption = r"\textbf{FIXTURE DATA -- not results.} " + caption
    lines = [
        f"% {name}.tex -- GENERATED by paper/tables/make_tables.py; do not edit.",
        "% Inputs: " + (", ".join(sorted(out.inputs)) or "none"),
    ]
    lines += [f"% MISSING input: {item}" for item in sorted(set(out.missing))]
    size, gap = DENSE if dense else ("footnotesize", 3)
    lines += [rf"\begin{{{env}}}[t]", r"\centering", "\\" + size,
              rf"\setlength{{\tabcolsep}}{{{gap}pt}}", rf"\caption{{{caption}}}",
              rf"\label{{tab:{name}}}", body]
    if note:
        lines.append(r"\\[2pt]{\scriptsize " + note + "}")
    lines.append(rf"\end{{{env}}}")
    return "\n".join(lines) + "\n"


def placeholder(name: str, caption: str, out: "g.Output", *, wide: bool) -> str:
    missing = ", ".join(sorted(set(out.missing))) or "input"
    body = "\n".join([r"\begin{tabular}{l}", r"\hline",
                      rf"\textbf{{{g.MISSING_TEXT}: {esc(missing)}}} \\",
                      r"\hline", r"\end{tabular}"])
    return float_env(name, caption, body, wide=wide, out=out)


#: The demand-only Belady/MIN reference row of the disk tables.
BELADY = "belady_min"


def policy_label(policy: str, latency: str = g.HEADLINE_LATENCY) -> str:
    text = esc(policy)
    if policy == BELADY:
        return text + r"$^\ddagger$"
    return text + r"$^\dagger$" if latency != g.HEADLINE_LATENCY else text


def sorted_policies(rows) -> list[dict]:
    return sorted(rows, key=lambda r: (r.get("latency") != g.HEADLINE_LATENCY,
                                       g.policy_key(r["policy"])))


def _headline(rows, **criteria):
    return g.select(rows, config=g.HEADLINE_CONFIG, merge=g.HEADLINE_MERGE, **criteria)


