def _web_value(payload: dict | None, *names):
    """A top-level or one-level-nested numeric key of the schema-less web
    profile, or None. Never a guessed value."""
    if not payload:
        return None
    for name in names:
        if isinstance(payload.get(name), (int, float)):
            return payload[name]
        for value in payload.values():
            if isinstance(value, dict) and isinstance(value.get(name), (int, float)):
                return value[name]
    return None


def t1_datasets(results, out):
    caption = ("Datasets. Disk: oracleGeneral block traces per corpus, canonical request "
               "reconstruction (records are requests; FIU 4\\,KiB pages are merged up to "
               "the stated sector cap). Web: the RetailRocket event log. Writes replay as "
               "reads: oracleGeneral carries no operation flag.")
    rows = results.rows("disk/corpus_profile.csv", out)
    web = results.json_object("web/dataset_profile.json", out)
    if rows is None and web is None:
        return placeholder("t1_datasets", caption, out, wide=True)
    table = Table("llrrrlrrrr", ["Dataset", "Corpus", "Traces", "Records", "Requests",
                                 "Reconstruction", "Mean blocks", "Contig.\\ (\\%)",
                                 "Hours (med.)", "Twins / subset"])
    by_corpus = defaultdict(list)
    for row in rows or ():
        by_corpus[row["corpus"]].append(row)
    for corpus in sorted(by_corpus):
        items = by_corpus[corpus]
        caps = sorted({r["max_merge_sectors"] for r in items if r["max_merge_sectors"]})
        units = "/".join(sorted({r["size_unit"] for r in items}))
        # Records become requests only where pages were merged (FIU); every
        # other corpus records one request per record, whatever cap is stored.
        merged = sum(r["records"] for r in items) != sum(r["requests"] for r in items)
        rule = (f"pages merged, cap {'/'.join(map(str, caps))}" if merged and caps
                else "as recorded")
        table.row(["Block traces", esc(corpus), fcount(len(items)),
                   fcount(sum(r["records"] for r in items)),
                   fcount(sum(r["requests"] for r in items)),
                   rule + f" ({esc(units)})",
                   fnum(statistics.fmean(r["mean_request_blocks"] for r in items), 1),
                   fnum(100 * statistics.fmean(r["contiguous_fraction"] for r in items), 1),
                   fnum(statistics.median(r["hours_covered"] for r in items), 1),
                   f"{fcount(sum(r['twin_group'] is not None for r in items))} / "
                   f"{fcount(sum(r['paper_subset'] for r in items))}"])
    if rows is None:
        table.row(["Block traces", rf"\textbf{{{g.MISSING_TEXT}: disk/corpus\_profile.csv}}"]
                  + [DASH] * 8)
    if web is None:
        table.row(["RetailRocket", "web", DASH,
                   rf"\textbf{{{g.MISSING_TEXT}: web/dataset\_profile.json}}"] + [DASH] * 6)
    else:
        sessions = _web_value(web, "sessions", "n_sessions")
        table.row(["RetailRocket", "web", "1",
                   fcount(_web_value(web, "raw_rows", "events", "n_events")),
                   fcount(_web_value(web, "views", "n_views")),
                   (f"{fcount(sessions)} sessions" if sessions is not None else DASH),
                   DASH, DASH, DASH, DASH])
    return float_env("t1_datasets", caption, table.latex(), wide=True, out=out, dense=True,
                     note="Records: raw oracleGeneral records (web: raw event rows). Requests: "
                          "canonical requests (web: product views). Merge caps in 512-B "
                          "sectors; record sizes in bytes or sectors as noted.")


def t1b_hardware(results, out):
    caption = ("Hardware of the measurement host and the calibrated devices "
               "(QD1 O\\_DIRECT; $\\kappa = t_{pos}/t_{xfer}$ per 512-B block).")
    devices = results.glob("realio/device_*.json", out)
    host = None
    for study in ("disk", "realio", "web", "live", "gpu"):
        record = results.provenance(study)
        if record and record.get("host"):
            host = record
            results.note_input(out, f"{study}/provenance.json")
            break
    if not devices and host is None:
        return placeholder("t1b_hardware", caption, out, wide=True)
    table = Table("lllrrr", ["Item", "Model", "Type", "Rand.\\ 4K p50 ($\\mu$s)",
                             "Seq.\\ 1M (MB/s)", "$\\kappa$"])
    if host is not None:
        info = host["host"]
        table.row(["Host", esc(info.get("platform", DASH)),
                   f"{fcount(info.get('cpu_count'))} CPUs", DASH, DASH, DASH])
        gpu = (results.provenance("gpu") or {}).get("gpu")
        if isinstance(gpu, list) and gpu:
            table.row(["GPU", esc(gpu[0].get("name", DASH)), "shared", DASH, DASH, DASH])
    for relative, row in devices.items():
        kind = {True: "rotational", False: "solid state", None: DASH}[row["rotational"]]
        table.row([esc(row["device"]), esc(row["model"] or DASH), kind,
                   fnum(row["rand4k_p50_us"], 0), fnum(row["seq1m_MBps"], 1),
                   fnum(row["kappa"], 0)])
    if not devices:
        table.row([rf"\textbf{{{g.MISSING_TEXT}: realio/device\_*.json}}"] + [DASH] * 5)
    return float_env("t1b_hardware", caption, table.latex(), wide=True, out=out)


