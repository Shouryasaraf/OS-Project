def _primary_device(results, out, rows) -> str:
    devices = results.glob("realio/device_*.json", out, required=False)
    rotational = [d["device"] for d in devices.values() if d["rotational"]]
    present = g.distinct(rows, "device")
    for device in rotational:
        if device in present:
            return device
    return present[0]


def t3_realio(results, out, trace: str = "msr_hm_0"):
    caption = ("Real-device validation (measured). One device and trace; Backend B (odirect) "
               "replays the simulator's plan with asserted parity, Backend A (pagecache) "
               "runs through the kernel page cache. Latencies are means over repeats with "
               "95\\% CIs over repeats; k: effective prefetch multiple.")
    rows = results.rows("realio/realio_summary.csv", out)
    if not rows:
        return placeholder("t3_realio", caption, out, wide=True)
    device = _primary_device(results, out, rows)
    traces = g.distinct(g.select(rows, device=device), "trace")
    trace = trace if trace in traces else traces[0]
    items = g.select(rows, device=device, trace=trace)
    reps = sorted({r["reps"] for r in items})
    table = Table("llrrrrrrrrr", ["Backend", "Mode", "Sim.\\ hit", "Real hit", "Full-hit",
                                  "Mean ($\\mu$s)", "p50", "p99", "Late", "Dev.\\ MiB", "k"])
    for think in g.distinct(items, "think"):
        table.group(f"think time {esc(think)}")
        for row in sorted(g.select(items, think=think),
                          key=lambda r: (r["backend"], g.policy_key(r["mode"]))):
            table.row([esc(row["backend"]), esc(row["mode"]),
                       fpct(row["sim_hit_ratio"]).replace(r"\,\%", ""),
                       fpct(row["real_hit_ratio"]).replace(r"\,\%", ""),
                       fpct(row["full_hit_request_frac"]).replace(r"\,\%", ""),
                       ci_cell(row["lat_mean_us"], row["lat_mean_us_lo"], row["lat_mean_us_hi"],
                               fnum, digits=0),
                       fnum(row["lat_p50_us"], 0), fnum(row["lat_p99_us"], 0),
                       fnum(row["late_hits"], 0), fnum(row["device_MiB"], 1),
                       fnum(row["k_eff"], 2)])
    return float_env("t3_realio", caption + f" Device {esc(device)}, trace {esc(trace)}, "
                     f"{fcount(items[0]['requests'])} requests, "
                     f"{'/'.join(map(str, reps))} repeats; hit ratios in \\%.",
                     table.latex(), wide=True, out=out)


def t3b_realio_summary(results, out):
    caption = ("Simulator against measurement per device, backend, think model and trace: "
               "Spearman rank correlation across modes of measured mean latency with simulated "
               "device time and with simulated hit ratio, and the mean prediction error of the "
               "hit-ratio-based latency prediction. Stated per trace, not as a device property.")
    rows = results.rows("realio/realio_summary.csv", out)
    if not rows:
        return placeholder("t3b_realio_summary", caption, out, wide=True)
    table = Table("llllrrrrr", ["Device", "Backend", "Think", "Trace", "Modes",
                                "$\\rho$ dev.\\ time", "$\\rho$ hit", "Pred.\\ err.\\ (\\%)",
                                "Foreign I/O (\\%)"])
    groups = defaultdict(list)
    for row in rows:
        groups[(row["device"], row["backend"], row["think"], row["trace"])].append(row)
    for (device, backend, think, trace), items in sorted(groups.items()):
        errors = [r["pred_err"] for r in items if r["pred_err"] is not None]
        foreign = [r["foreign_io_frac_max"] for r in items if r["foreign_io_frac_max"] is not None]
        table.row([esc(device), esc(backend), esc(think), esc(trace), fcount(len(items)),
                   fnum(items[0]["spearman_device_time"], 2, sign=True),
                   fnum(items[0]["spearman_hit_ratio"], 2, sign=True),
                   fnum(100 * statistics.fmean(errors), 1, sign=True) if errors else DASH,
                   fnum(100 * max(foreign), 2) if foreign else DASH])
    return float_env("t3b_realio_summary", caption, table.latex(), wide=True, out=out)


