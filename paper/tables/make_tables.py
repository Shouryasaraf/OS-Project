@g.traced_formatter
def t9_absolute(v) -> str:
    return fnum(100.0 * v, 2)


@g.traced_formatter
def t9_signed0(v) -> str:
    return fnum(v, 0, sign=True)


@g.traced_formatter
def t9_signed2(v) -> str:
    return fnum(v, 2, sign=True)


@g.traced_formatter
def t9_fine(v) -> str:
    return fpp(v, 3)


def _interval_text(label, estimate, lo, hi, statistic) -> str:
    formatter = {"difference": fpp, "difference_fine": t9_fine, "ratio": fratio,
                 "absolute": t9_absolute, "us": t9_signed0, "ms": t9_signed2,
                 "rho": t9_signed2}[statistic]
    unit = {"difference": " pp", "difference_fine": " pp", "absolute": " pp",
            "us": r" $\mu$s",
            "ms": " ms"}.get(statistic, "")
    parts = []
    if estimate is not None:
        parts.append(formatter(estimate).replace(r"\,pp", ""))
    if lo is not None and hi is not None:
        parts.append(fci(lo, hi, formatter))
    text = " ".join(parts) + unit
    return (esc(label) + " " + text) if label else text


def _tex(text: str) -> str:
    """Escape a verdict or note, with its comparison signs in math mode
    (a bare < or | prints as another glyph in IEEEtran's OT1 text font)."""
    return (esc(text).replace(" < ", " $<$ ").replace(" - ", " $-$ ")
            .replace(" / ", " $/$ "))


def _tally(decisions) -> str:
    counts = defaultdict(int)
    for d in decisions:
        counts[d.verdict.split(" (")[0]] += 1
    return "; ".join(f"{_tex(verdict)}: {fcount(n)}" for verdict, n in
                     sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])))


